import { build } from 'esbuild'
import { copyFile, mkdir } from 'node:fs/promises'
import { resolve } from 'node:path'

const destination = resolve(process.argv[2])
await mkdir(destination, { recursive: true })
await build({
  entryPoints: ['src/dawn/markdown.ts'],
  bundle: true,
  minify: true,
  format: 'iife',
  globalName: 'DawnMarkdown',
  outfile: resolve(destination, 'markdown.js'),
  banner: {
    js: '/*! Generated by dawn-admin build:chat-assets; markdown-it MIT License, see markdown.LICENSE */'
  }
})
await copyFile('src/dawn/markdown.css', resolve(destination, 'markdown.css'))
await copyFile('node_modules/markdown-it/LICENSE', resolve(destination, 'markdown.LICENSE'))
